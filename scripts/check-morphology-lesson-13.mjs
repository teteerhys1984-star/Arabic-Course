assert.match(component, /SolutionsArea test=\{testDefinition\} mode="teacher"/)
assert.ok(!readdirSync('src/lessons/morphology-lesson-13').some((name) => /\.test\.(ts|tsx)$/.test(name)), 'no unit test folder/file is created for the morphology lesson')
assert.ok(!registrySource.includes("id: 'morphology-unit-test'"), 'no morphology unit test may be registered')

assert.ok(component.includes('غَافِر') && component.includes('غَفَّار') && component.includes('مَغْفُور'))
