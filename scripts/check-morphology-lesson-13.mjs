assert.equal(weights.length, 5)
for (const [pattern, examples] of [
  ['فَعَّال', ['غَفَّار', 'كَذَّاب', 'تَوَّاب']],
  ['مِفْعَال', ['مِقْدَام', 'مِعْطَاء', 'مِهْذَار']],
  ['فَعُول', ['صَبُور', 'شَكُور', 'غَفُور']],
  ['فَعِيل', ['عَلِيم', 'رَحِيم', 'سَمِيع']],
  ['فَعِل', ['حَذِر', 'فَطِن', 'يَقِظ']],
]) {
  const item = weights.find((weight) => weight.pattern === pattern)
  assert.ok(item, `missing weight ${pattern}`)
  for (const example of examples) assert.ok(item.examples.includes(example), `missing example ${example}`)
  assert.ok(item.sentence && item.meaning && item.answer)
}
