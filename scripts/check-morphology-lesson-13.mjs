assert.equal(registered.length, 1, 'the lesson id must be registered exactly once')
assert.equal(registered[0].number, '١٣')
assert.equal(registered[0].title, 'صِيَغُ المبالغة')
assert.equal(registered[0].sectionId, 'morphology', 'lesson 13 must belong to morphology only')
assert.equal(morph.length, 13)
