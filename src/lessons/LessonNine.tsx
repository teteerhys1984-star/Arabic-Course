/* ------------------------------------------------------------------ *
 * مراجعة أسئلة المصدر (1–27): تُعرض للمراجعة، والحل النموذجي بكشف اختياري
 * ------------------------------------------------------------------ */

const sourcePlaceholders: Record<SourceQuestionType, string> = {
  choice: 'اختر الإجابة',
  'true-false': 'اختر الحكم',
  parse: 'اكتب الإعراب كاملًا',
  correct: 'اكتب الجملة الصحيحة',
  open: 'اكتب إجابتك',
}

function SourceReview({ from, to }: { from: number; to: number }) {
  const questions = sourceQuestions.filter(
    (question) => question.number >= from && question.number <= to,
  )
  const [answers, setAnswers] = useState<Record<string, string>>({})
  const [revealed, setRevealed] = useState<Record<number, boolean>>({})
  const allRevealed = questions.every((question) => revealed[question.number])

  function toggle(number: number) {
    setRevealed((current) => ({ ...current, [number]: !current[number] }))
  }

  return (
    <section className="lesson-nine-source-review" data-testid={`lesson9-source-review-${from}`}>
      <div className="lesson-nine-source-review__heading">
        <div>
          <p className="card__eyebrow">من المادة المصدرية</p>
          <h3>أسئلة نهاية الدرس في المصدر: <bdi>{from}–{to}</bdi></h3>
        </div>
        <button
          type="button"
          className="button button--ghost"
          onClick={() =>
            setRevealed(
              allRevealed
                ? {}
                : Object.fromEntries(questions.map((question) => [question.number, true])),
            )
          }
        >
          {allRevealed ? 'إخفاء الإجابات' : 'أظهر الإجابات النموذجية'}
        </button>
      </div>

      <p className="lesson-nine-note">
        هذه أسئلة المصدر للمراجعة، وليست اختبار المنصة النهائي؛ فاختبار الدرس التاسع خطوة مستقلة
        بأسئلة جديدة.
      </p>

      {questions.flatMap((question, index, list) => {
        const showHeading = index === 0 || list[index - 1].section !== question.section
        const rows: ReactNode[] = []
        if (showHeading) rows.push(<h3 key={`section-${question.section}`}>{question.section}</h3>)
        rows.push(
          <fieldset
            className="official-question lesson-nine-source-question"
            key={question.number}
            data-testid={`lesson9-source-q${question.number}`}
          >
            <legend>
              <span className="question-number">السؤال <bdi>{question.number}</bdi></span> <bdi>{question.prompt}</bdi>
            </legend>
            {question.instruction && (
              <p className="lesson-nine-source-instruction">{question.instruction}</p>
            )}

            {(question.type === 'choice' || question.type === 'true-false') && question.options ? (
              <div className="official-options">
                {question.options.map((option) => (
                  <label key={option}>
                    <input
                      type="radio"
                      name={`lesson9-source-q${question.number}`}
                      value={option}
                      checked={answers[`${question.number}`] === option}
                      onChange={() => setAnswers((current) => ({ ...current, [`${question.number}`]: option }))}
                    />
                    <span><bdi>{option}</bdi></span>
                  </label>
                ))}
              </div>
            ) : (
              <textarea
                rows={3}
                value={answers[`${question.number}`] ?? ''}
                onChange={(event) =>
                  setAnswers((current) => ({ ...current, [`${question.number}`]: event.target.value }))
                }
                aria-label={`إجابة السؤال ${question.number}`}
                placeholder={sourcePlaceholders[question.type]}
              />
            )}

            <button
              type="button"
              className="button button--ghost lesson-nine-reveal"
              onClick={() => toggle(question.number)}
            >
              {revealed[question.number] ? 'إخفاء الإجابة النموذجية' : 'أظهر الإجابة النموذجية'}
            </button>

            {revealed[question.number] && (
              <div className="lesson-nine-feedback is-good">
                <strong>الإجابة النموذجية</strong>
                <p><bdi>{question.answer}</bdi></p>
                {question.parsing && <FullParsing lines={question.parsing} />}
                {question.note && <p className="lesson-nine-teacher-note">{question.note}</p>}
              </div>
            )}
          </fieldset>,
        )
        return rows
      })}
    </section>
  )
}

