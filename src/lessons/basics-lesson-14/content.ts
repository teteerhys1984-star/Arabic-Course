const past = (word: string) => `${word}: فعل ماضٍ مبني على الفتح الظاهر على آخره.`
const pastT = (word: string) =>
  `${word}: فعل ماضٍ مبني على السكون لاتصاله بتاء الفاعل، والتاء ضمير متصل مبني على الضم في محل رفع فاعل.`
const order = (word: string) =>
  `${word}: فعل أمر مبني على السكون، والفاعل ضمير مستتر وجوبًا تقديره أنتَ.`
