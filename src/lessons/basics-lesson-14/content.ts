/** إعراب كامل لاسم من الأسماء الخمسة: الكلمة ثم موقعها (فاعل/مبتدأ/خبر/نعت…). */
const fiveRaised = (word: string, role: string) =>
  `${word}: ${role} مرفوع وعلامة رفعه الواو؛ لأنه من الأسماء الخمسة، وهو مضاف، ${kaf}`
const fiveAccused = (word: string, role: string) =>
  `${word}: ${role} منصوب وعلامة نصبه الألف؛ لأنه من الأسماء الخمسة، وهو مضاف، ${kaf}`
const fiveGenitive = (word: string, role: string, preposition: string) =>
  `${word}: ${role} مجرور بـ«${preposition}» وعلامة جرّه الياء؛ لأنه من الأسماء الخمسة، وهو مضاف، ${kaf}`

