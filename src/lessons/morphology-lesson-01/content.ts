const OBJ_CHOICE = (label: string, options: string[], answer: string): TestField => ({
  kind: 'choice',
  label,
  options,
  answer,
})

const ROOT = (accept: string[]): TestField => ({
  kind: 'text',
  label: 'الجذر',
  accept,
  placeholder: 'مثال: ك ت ب',
})

const ESSAY = (label: string, placeholder = 'اكتب إجابتك بعبارتك الخاصة...'): TestField => ({
  kind: 'essay',
  label,
  placeholder,
})

function tf(id: string, number: number, prompt: string, answer: 'صح' | 'خطأ', explanation: string, teacherAnswer: string): MorphTestQuestion {
  return {
    id,
    number,
    type: 'صح أو خطأ',
    prompt,
    fields: [{ kind: 'choice', label: 'الحكم', options: ['صح', 'خطأ'], answer }],
    explanation,
    teacherAnswer,
  }
}

function mcq(id: string, number: number, prompt: string, options: string[], answer: string, explanation: string): MorphTestQuestion {
  return {
    id,
    number,
    type: 'اختيار من متعدد',
    prompt,
    fields: [OBJ_CHOICE('الإجابة', options, answer)],
    explanation,
    teacherAnswer: `الإجابة: ${answer}. ${explanation}`,
  }
}

function rootQ(id: string, number: number, prompt: string, accept: string[], explanation: string): MorphTestQuestion {
  return {
    id,
    number,
    type: 'استخراج الجذر',
    prompt,
    fields: [ROOT(accept)],
    explanation,
    teacherAnswer: `الجذر: ${accept[0]}. ${explanation}`,
  }
}

function essayQ(
  id: string,
  number: number,
  type: QuestionType,
  prompt: string,
  explanation: string,
  teacherAnswer: string,
): MorphTestQuestion {
  return {
    id,
    number,
    type,
    prompt,
    fields: [ESSAY('الإجابة')],
    explanation,
    teacherAnswer,
  }
}

