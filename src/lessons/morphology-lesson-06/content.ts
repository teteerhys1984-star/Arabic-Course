/* ------------------------------------------------------------------ *
 * مقابلة الحروف بالميزان — السابقة المعتمدة في الدرس الثاني
 * (MappingRow: حرف أصلي يقابله حرف ميزان، أو حرف زائد بلا مقابل أصلي).
 * ------------------------------------------------------------------ */

export interface MappingRow {
  /** حرف الكلمة كما يُكتب. */
  letter: string
  /** حرف الميزان المقابل، أو «—» للحرف الزائد. */
  pattern: string
  /** الحرف زائد في هذه الصيغة. */
  extra?: boolean
  /** ملاحظة على الحرف (لام ثانية، تاء زيادة…). */
  note?: string
}

/** حرف أصلي يقابله حرف من الميزان. */
const m = (letter: string, pattern: string, note?: string): MappingRow => ({ letter, pattern, note })
/** حرف زائد في الصيغة (يُثبت في الوزن كما هو في موضعه — ت-6). */
const x = (letter: string, note?: string): MappingRow => ({ letter, pattern: '—', extra: true, note })

/** تحليل صرفي كامل لفعل من أفعال الدرس. */
export interface VerbAnalysis {
  id: string
  /** الفعل مضبوطًا. */
  word: string
  /** نوعه كما يقرّره الدرس. */
  kind: 'رباعي مجرّد' | 'رباعي مزيد'
  /** جذره الرباعي (حروف منفصلة بلا تشكيل — حدود الضبط المعتمدة). */
  root: string
  /** أحرفه الأصلية كما يعرضها المصدر. */
  rootLetters: string
  /** عدد حروفه الظاهرة. */
  visibleCount: number
  /** عدد أحرفه الأصلية. */
  rootCount: number
  /** الحرف الزائد، أو «لا يوجد». */
  extraLetter: string
  /** وزنه الصرفي. */
  weight: string
  /** مقابلة الحرف بالحرف. */
  rows: readonly MappingRow[]
  /** تعليل المعلّم. */
  teacherNote: string
}

