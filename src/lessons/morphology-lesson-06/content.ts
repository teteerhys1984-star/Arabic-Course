const ARABIC_INDIC = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩']

/** أرقام عربية مشرقية للعرض فقط (لا تُستعمل في المفاتيح). */
export function arabicDigits(value: number | string): string {
  return String(value).replace(/[0-9]/g, (digit) => ARABIC_INDIC[Number(digit)])
}

