/** تحليل فعل بمعرفه (`dahraja`) أو بصيغته المضبوطة (`دَحْرَجَ`). */
export function analysisOf(idOrWord: string): VerbAnalysis {
  const found = verbAnalyses.find((verb) => verb.id === idOrWord || verb.word === idOrWord)
  if (!found) throw new Error(`Unknown verb analysis: ${idOrWord}`)
  return found
}

