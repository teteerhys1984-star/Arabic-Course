  /** القسم العام. */
  kind: 'صحيح' | 'معتلّ'
  /** النوع المفصَّل. */
  type: string
  /** الحروف الأصلية كما تُكتب (حروف منفصلة بلا تشكيل — حدود الضبط المعتمدة). */
