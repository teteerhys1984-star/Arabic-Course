/** تحليل فعل بمعرفه أو بصيغته المضبوطة. */
export function factOf(idOrWord: string): VerbFact {
  const found = verbFacts.find((verb) => verb.id === idOrWord || verb.word === idOrWord)
  if (!found) throw new Error(`Unknown verb fact: ${idOrWord}`)
  return found
}

