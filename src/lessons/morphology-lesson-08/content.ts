export function conjugationFor(id: string): Conjugation {
  const row = conjugations.find((item) => item.id === id)
  if (!row) throw new Error(`Unknown conjugation: ${id}`)
  return row
}

export function arabicDigits(value: number): string {
  return String(value).replace(/\d/g, (digit) => '٠١٢٣٤٥٦٧٨٩'[Number(digit)])
}

/** Keep every combining mark attached to its letter. Highlight is visual, NOT grammatical segmentation. */
export function verbParts(word: string, tense: Tense): { beginning: string; middle: string; ending: string } {
  const letters = word.match(/\P{M}\p{M}*/gu) ?? []
  const start = tense === 'past' ? 0 : 1
  const end = tense === 'past' ? 2 : 3
  return { beginning: letters.slice(0, start).join(''), middle: letters.slice(start, end).join(''), ending: letters.slice(end).join('') }
}

