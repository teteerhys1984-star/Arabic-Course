function choice(options: string[], answer: string): TestField {
  return { kind: 'choice', options, answer }
}
function select(label: string, options: string[], answer: string): TestField {
  return { kind: 'select', label, options, answer }
}
function multi(label: string, options: string[], answers: string[]): TestField {
  return { kind: 'multi', label, options, answers }
}
function question(
  number: number,
  level: string,
  prompt: string,
  fields: TestField[],
  solution: string,
  rule: string,
  explanation: string,
): TestQuestion {
  return {
    id: `morph9-q${String(number).padStart(2, '0')}`,
    number,
    level,
    prompt,
    fields,
    solution,
    rule,
    explanation,
    answerSource: 'platform',
    type:
      fields.length > 1
        ? 'مطابقة مزدوجة'
        : fields[0].kind === 'multi'
          ? 'اختيار متعدد'
          : 'اختر الإجابة',
  }
}

