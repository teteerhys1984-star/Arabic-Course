export function arabicDigits(value: number): string {
  return String(value).replace(/\d/g, (digit) => '٠١٢٣٤٥٦٧٨٩'[Number(digit)])
}

export function arrowPair(text: string): { verb: string; masdar: string } {
  const [verb, masdar] = text.split('←').map((part) => part.trim())
  return { verb, masdar: masdar ?? '' }
}

