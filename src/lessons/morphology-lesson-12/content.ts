function choiceQuestion(
  id: string,
  number: number,
  section: string,
  prompt: string,
  options: string[],
  answer: string,
  rule: string,
  explanation: string,
  sentence?: string,
): TestQuestion {
  return {
    id,
    number,
    level: section,
    type: 'اختيار من متعدد',
    prompt,
    ...(sentence ? { sentence } : {}),
    fields: [{ kind: 'choice', options, answer }],
    solution: answer,
    rule,
    explanation,
    answerSource: 'platform',
  }
}

