function makeChoiceQuestion(
  number: number,
  level: string,
  prompt: string,
  options: [string, string, string],
  answer: string,
  rule: string,
  explanation: string,
  example: string,
): TestQuestion {
  const id = `spell8-exam-${String(number).padStart(2, '0')}`
  return {
    id,
    number,
    type: 'اختيار من متعدد',
    level,
    prompt,
    fields: [{ kind: 'choice', options, answer }],
    solution: answer,
    rule,
    explanation,
    example,
    answerSource: 'platform',
    teacherAnswer: `${answer} — ${rule} ${explanation}`,
  }
}

